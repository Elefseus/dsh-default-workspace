/**
 * Frame-level Zstandard helpers for DSH append-only Session logs.
 *
 * Node's `node:zlib` Zstandard API decodes exactly one frame: feeding a
 * concatenated log (DSH appends one frame per write batch) to the public stream
 * decoder fails with `ZSTD_error_prefix_unknown`, and `zstdDecompressSync`
 * silently stops after the first frame. A DSH log is a frame sequence, so the
 * container has to be walked before anything can be decoded.
 *
 * The Host additionally *requires the first frame to be exactly one header line*:
 * `assertZstdHeaderFrame` throws "first frame is not exactly one header line" and
 * listing then skips the log silently. A log whose header shares a frame with
 * events is therefore invisible until it is re-framed.
 */
import { zstdCompressSync, zstdDecompressSync } from 'node:zlib';

const ZSTD_MAGIC = 0xfd2fb528;
const SKIPPABLE_MASK = 0xfffffff0;
const SKIPPABLE_MAGIC = 0x184d2a50;
const DICT_ID_SIZE = [0, 1, 2, 4];
const FCS_SIZE = [0, 2, 4, 8];

/** Largest payload per re-framed event chunk. */
const REFRAME_CHUNK_BYTES = 1 << 20;

/**
 * Split a concatenated Zstandard buffer into frames.
 * @param buf - the whole artifact contents.
 * @returns frames as `{ start, end, skippable }` byte ranges, in file order.
 */
export function scanFrames(buf) {
  const frames = [];
  let pos = 0;
  while (pos < buf.length) {
    const start = pos;
    if (buf.length - pos < 4) throw new Error(`truncated zstd frame header at byte ${pos}`);
    const magic = buf.readUInt32LE(pos);
    if (((magic & SKIPPABLE_MASK) >>> 0) === SKIPPABLE_MAGIC) {
      if (buf.length - pos < 8) throw new Error(`truncated skippable frame at byte ${pos}`);
      const size = buf.readUInt32LE(pos + 4);
      pos += 8 + size;
      if (pos > buf.length) throw new Error(`truncated skippable frame at byte ${pos}`);
      frames.push({ start, end: pos, skippable: true });
      continue;
    }
    if (magic !== ZSTD_MAGIC) throw new Error(`not a zstd frame at byte ${pos} (magic 0x${magic.toString(16)})`);
    pos += 4;
    const descriptor = buf[pos];
    pos += 1;
    const fcsFlag = descriptor >> 6;
    const singleSegment = (descriptor >> 5) & 0x1;
    const checksum = (descriptor >> 2) & 0x1;
    const dictFlag = descriptor & 0x3;
    if (!singleSegment) pos += 1; // Window_Descriptor
    pos += DICT_ID_SIZE[dictFlag];
    pos += fcsFlag === 0 ? (singleSegment ? 1 : 0) : FCS_SIZE[fcsFlag];
    for (;;) {
      if (buf.length - pos < 3) throw new Error(`truncated block header at byte ${pos}`);
      const header = buf[pos] | (buf[pos + 1] << 8) | (buf[pos + 2] << 16);
      pos += 3;
      const last = header & 0x1;
      const type = (header >> 1) & 0x3;
      const size = header >>> 3;
      if (type === 3) throw new Error(`reserved zstd block type at byte ${pos - 3}`);
      pos += type === 1 ? 1 : size; // an RLE block stores a single byte
      if (pos > buf.length) throw new Error(`truncated zstd block body at byte ${pos}`);
      if (last) break;
    }
    if (checksum) pos += 4;
    if (pos > buf.length) throw new Error(`truncated zstd frame at byte ${pos}`);
    frames.push({ start, end: pos, skippable: false });
  }
  return frames;
}

/** Decode every frame and concatenate the regenerated bytes. */
export function decodeLog(buf) {
  const frames = scanFrames(buf);
  const parts = [];
  for (const frame of frames) {
    if (frame.skippable) continue;
    parts.push(zstdDecompressSync(buf.subarray(frame.start, frame.end)));
  }
  return { text: Buffer.concat(parts), frames };
}

/** Whether one decoded first frame holds exactly the header line, as the Host demands. */
export function isHeaderFrame(plaintext) {
  return plaintext.length > 0 && plaintext.indexOf(0x0a) === plaintext.length - 1;
}

/** Split a decoded log into its header line (without the newline) and the remaining bytes. */
export function splitHeader(text) {
  const newline = text.indexOf(0x0a);
  if (newline < 0) throw new Error('log has no complete header line');
  return { headerLine: text.subarray(0, newline), rest: text.subarray(newline + 1) };
}

/** Re-emit event bytes as a sequence of newline-aligned frames. */
function chunkFrames(rest) {
  const frames = [];
  let start = 0;
  while (start < rest.length) {
    let end = Math.min(rest.length, start + REFRAME_CHUNK_BYTES);
    if (end < rest.length) {
      const newline = rest.lastIndexOf(0x0a, end - 1);
      if (newline >= start) end = newline + 1;
    }
    frames.push(zstdCompressSync(rest.subarray(start, end)));
    start = end;
  }
  return frames;
}

/**
 * Rewrite one Session log's header without touching a single event byte.
 *
 * The canonical shape is preserved byte-for-byte: the header frame is decoded,
 * re-emitted with the mutated header, and every later frame is copied as-is.
 * A log whose first frame is not exactly one header line (for example a log that
 * was re-compressed as one large frame) is re-framed: its bytes are decoded once,
 * then re-emitted as a header frame plus newline-aligned event frames.
 *
 * @param buf - the whole artifact contents.
 * @param mutateHeader - receive the parsed header, return the value to write.
 * @returns the rebuilt artifact, the original header and the mode used.
 */
export function rewriteHeader(buf, mutateHeader) {
  const decoded = decodeLog(buf);
  const { headerLine, rest } = splitHeader(decoded.text);
  const header = JSON.parse(headerLine.toString('utf8'));
  const next = mutateHeader(header) ?? header;
  const line = Buffer.from(JSON.stringify(next), 'utf8');
  const headerFrame = zstdCompressSync(Buffer.concat([line, Buffer.from('\n')]));

  const frames = decoded.frames;
  const canonical = frames.length > 0 && !frames[0].skippable && isHeaderFrame(zstdDecompressSync(buf.subarray(frames[0].start, frames[0].end)));
  if (canonical) {
    const tail = buf.subarray(frames[1]?.start ?? frames[0].end);
    return { output: Buffer.concat([headerFrame, tail]), header, mode: 'preserved', frames: frames.length };
  }
  return { output: Buffer.concat([headerFrame, ...chunkFrames(rest)]), header, mode: 'reframed', frames: frames.length };
}

/**
 * Report whether one stored log is readable by the Host and decode it when asked.
 * @param buf - the whole artifact contents.
 * @returns `{ readable, header, rest, frames, reason }`.
 */
export function inspectLog(buf) {
  const { text, frames } = decodeLog(buf);
  let headerLine;
  let rest;
  try {
    ({ headerLine, rest } = splitHeader(text));
  } catch (error) {
    return { readable: false, frames: frames.length, reason: error.message };
  }
  const header = JSON.parse(headerLine.toString('utf8'));
  const first = frames[0];
  if (first === undefined || first.skippable) return { readable: false, header, rest, frames: frames.length, reason: 'log starts with a skippable frame' };
  const firstText = zstdDecompressSync(buf.subarray(first.start, first.end));
  if (!isHeaderFrame(firstText)) {
    return { readable: false, header, rest, frames: frames.length, reason: 'first frame is not exactly one header line' };
  }
  return { readable: true, header, rest, frames: frames.length };
}
